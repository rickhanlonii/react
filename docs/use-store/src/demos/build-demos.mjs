// Builds the interactive explainers into docs/use-store/sandbox/explainers/generated/:
//
// - explainers.js: the page side, the one script a page includes;
// - <demo>.frame.js: the code each frame runs. React, ReactDOM and the
//   scheduler come from the frame's vendored build (require), everything
//   else is bundled from the frozen React build;
// - the "who re-renders" frames are compiled with the real React Compiler
//   (fixtures/store-bench/compiler-plugin.mjs, the same compiler build and
//   options as the benchmarks), and rerenders-code.json holds the source and
//   compiled code the page shows;
// - MANIFEST.json: which React build and compiler the files came from.
//
//   node docs/use-store/src/demos/build-demos.mjs
//   import {buildDemos} from './src/demos/build-demos.mjs'; await buildDemos();

import {build} from 'esbuild';
import crypto from 'crypto';
import fs from 'fs';
import path from 'path';
import {fileURLToPath, pathToFileURL} from 'url';

const here = path.dirname(fileURLToPath(import.meta.url));
const docs = path.resolve(here, '../..');
const repo = path.resolve(docs, '../..');
const bench = path.join(repo, 'fixtures/store-bench');

export const defaultOutDir = path.join(docs, 'sandbox/explainers/generated');
export const defaultReactBuild = path.join(bench, 'react-builds/head');

// Provided by the frame's vendored build. Everything else is bundled.
const frameModules = new Set(['react', 'react-dom', 'react-dom/client', 'scheduler']);

// Marks the frame's modules external by exact name (esbuild's `external`
// would also externalize react/jsx-runtime and friends), and resolves other
// React package paths to the frozen build.
function reactPlugin(reactBuild) {
  return {
    name: 'explainer-react',
    setup(b) {
      b.onResolve({filter: /^(react|react-dom|scheduler|use-sync-external-store)(\/.*)?$/}, args => {
        if (frameModules.has(args.path)) {
          return {path: args.path, external: true};
        }
        const [pkg, ...rest] = args.path.split('/');
        const sub = rest.length === 0 ? 'index.js' : rest.join('/') + '.js';
        const file = path.join(reactBuild, pkg, sub);
        if (!fs.existsSync(file)) {
          return {errors: [{text: 'Not in the React build: ' + args.path}]};
        }
        return {path: file};
      });
    },
  };
}

function hash(contents) {
  return crypto.createHash('sha256').update(contents).digest('hex').slice(0, 16);
}

// The text of a top-level function, from `function Name(` to the closing
// brace at the start of a line.
function extractFunction(code, name) {
  const start = code.search(new RegExp('^(export )?function ' + name + '\\(', 'm'));
  if (start === -1) {
    throw new Error('No function ' + name + ' in the code');
  }
  const end = code.indexOf('\n}', start);
  return code.slice(start, end + 2).replace(/^export /, '');
}

async function loadCompiler() {
  const plugin = await import(pathToFileURL(path.join(bench, 'compiler-plugin.mjs')).href);
  return plugin;
}

export async function buildDemos({
  outDir = defaultOutDir,
  reactBuild = defaultReactBuild,
  log = console.log,
} = {}) {
  if (!fs.existsSync(path.join(reactBuild, 'react/package.json'))) {
    throw new Error('Missing React build: ' + reactBuild);
  }
  const {compilerPlugin, compileSource, defaultCompilerPath} = await loadCompiler();
  fs.mkdirSync(outDir, {recursive: true});
  const files = {};

  const common = {
    bundle: true,
    format: 'iife',
    target: 'es2020',
    minify: false,
    legalComments: 'none',
    charset: 'utf8',
    jsx: 'automatic',
    define: {'process.env.NODE_ENV': '"development"'},
    logLevel: 'warning',
    write: false,
  };

  async function bundle(name, entry, plugins) {
    const result = await build({
      ...common,
      entryPoints: [path.join(here, entry)],
      outfile: path.join(outDir, name),
      plugins: [reactPlugin(reactBuild), ...plugins],
    });
    const contents = result.outputFiles[0].contents;
    const banner =
      '// Generated by docs/use-store/src/demos/build-demos.mjs from ' +
      'docs/use-store/src/demos/' +
      entry +
      '. Do not edit.\n';
    const text = banner + Buffer.from(contents).toString('utf8');
    fs.writeFileSync(path.join(outDir, name), text);
    files[name] = {bytes: Buffer.byteLength(text), sha256: hash(text)};
  }

  // The frames.
  await bundle('queue.frame.js', 'frames/entry-queue.js', []);
  await bundle('tearing.frame.js', 'frames/entry-tearing.js', []);
  await bundle('subscriptions.frame.js', 'frames/entry-subscriptions.js', []);

  const compileFilter = /\/src\/demos\/rerenders\/.*\.jsx$/;
  const compiled = () => compilerPlugin({filter: compileFilter});
  await bundle('rerenders-selectors.frame.js', 'rerenders/entry-selectors.js', [compiled()]);
  await bundle('rerenders-stores-compiler.frame.js', 'rerenders/entry-stores.js', [compiled()]);
  await bundle('rerenders-stores-nocompiler.frame.js', 'rerenders/entry-stores.js', []);

  // The code the "who re-renders" demo shows, compiled the same way.
  const compilerSource = fs.readFileSync(defaultCompilerPath);
  const compilerLabel =
    'babel-plugin-react-compiler dist, sha256 ' + hash(compilerSource);
  const code = {compiler: compilerLabel};
  for (const variant of ['selectors', 'stores']) {
    const file = path.join(here, 'rerenders', variant + '.jsx');
    const source = fs.readFileSync(file, 'utf8');
    const output = await compileSource(source, file);
    code[variant] = {
      row: extractFunction(source, 'Row'),
      compiledRow: extractFunction(output, 'Row'),
    };
  }
  const codeText = JSON.stringify(code, null, 2) + '\n';
  fs.writeFileSync(path.join(outDir, 'rerenders-code.json'), codeText);
  files['rerenders-code.json'] = {bytes: Buffer.byteLength(codeText), sha256: hash(codeText)};

  // The page side, which embeds rerenders-code.json.
  await bundle('explainers.js', 'runtime/explainers.js', []);

  const buildJson = path.join(reactBuild, 'BUILD.json');
  const manifest = {
    builtAt: new Date().toISOString(),
    react: {
      dir: path.relative(repo, reactBuild),
      version: JSON.parse(fs.readFileSync(path.join(reactBuild, 'react/package.json'), 'utf8')).version,
      sha: fs.existsSync(buildJson) ? JSON.parse(fs.readFileSync(buildJson, 'utf8')).sha : null,
    },
    compiler: {
      path: path.relative(repo, defaultCompilerPath),
      bytes: compilerSource.length,
      sha256: hash(compilerSource),
    },
    files,
  };
  fs.writeFileSync(path.join(outDir, 'MANIFEST.json'), JSON.stringify(manifest, null, 2) + '\n');
  log('built ' + Object.keys(files).length + ' explainer files into ' + path.relative(repo, outDir));
  return manifest;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  buildDemos().catch(error => {
    console.error(error);
    process.exit(1);
  });
}
