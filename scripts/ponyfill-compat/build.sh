#!/bin/sh
# Transpiles the fetched ponyfill sources (src/, from
# github.com/thejustinwalsh/react-concurrent-store packages/use-store/src at
# commit 2842481d49f6b54ed27bd6d0bb4b6973de6fd58e) into factories that take
# React as an argument, so the adapter can hand them the real React without
# going through the mocked 'react' module.
set -e
cd "$(dirname "$0")"
ESBUILD=../../node_modules/.bin/esbuild
mkdir -p dist
for pair in "experimental:src/experimental/index.ts" "stable:src/useStore.ts"; do
  name=${pair%%:*}
  entry=${pair#*:}
  $ESBUILD "$entry" --bundle --format=cjs --platform=neutral --jsx=transform \
    --external:react --target=es2019 --outfile=dist/$name.raw.js --log-level=warning
  {
    echo "'use strict';"
    echo "// Generated by build.sh from $entry. Do not edit."
    echo "module.exports = function createPonyfill(__React) {"
    echo "var module = {exports: {}}; var exports = module.exports;"
    echo "var require = function (id) { if (id === 'react') return __React; throw new Error('Unexpected require ' + id); };"
    cat dist/$name.raw.js
    echo "return module.exports;"
    echo "};"
  } > dist/$name.js
  rm dist/$name.raw.js
done
